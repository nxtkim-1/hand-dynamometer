// One session's report. Everything is recomputed from the saved raw readings, so a report always
// reflects the current analysis code. Print / Save as PDF uses the print stylesheet.

import { Link, useLocation, useParams } from "react-router-dom";
import { CentileChart, ForceChart } from "../components/Charts";
import { IconDownload, IconInfo, IconPrint, IconWarn } from "../components/Icons";
import { rawCsv, summaryCsv, download } from "../lib/exporters";
import { assess, normsFor } from "../lib/norms";
import { CALIBRATION_NOTE, fmt, summarize } from "../lib/protocol";
import { QUALITY_TEXT } from "../lib/quality";
import { getSession, type Session } from "../lib/storage";
import type { Hand } from "../lib/types";

const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

export default function ReportPage() {
  const { id } = useParams();
  const location = useLocation();
  const state = location.state as { session?: Session; saved?: boolean } | null;
  const session = (state?.session?.id === id ? state?.session : null) ?? (id ? getSession(id) : null);

  if (!session) {
    return (
      <div className="container">
        <div className="card empty" style={{ marginTop: 48 }}>
          <h1 style={{ fontSize: "1.6rem" }}>Report not found</h1>
          <p className="muted">Reports are kept only in the browser where the test was done. It may have been deleted, or opened on another device.</p>
          <div className="btn-row" style={{ justifyContent: "center" }}>
            <Link className="btn btn-primary" to="/test">
              Start a test
            </Link>
            <Link className="btn btn-secondary" to="/results">
              All results
            </Link>
          </div>
        </div>
      </div>
    );
  }
  return <Report session={session} notSaved={state?.saved === false} />;
}

function Report({ session, notSaved }: { session: Session; notSaved: boolean }) {
  const p = session.participant;
  const sum = summarize(session.trials);
  const a = assess(sum.overall_peak_kg, p.age, p.sex);
  const max = session.trials.filter((t) => t.step.test === "max");
  const fatigue = session.trials.find((t) => t.step.test === "fatigue");
  const date = new Date(session.created);
  const dateText = date.toLocaleString(undefined, { dateStyle: "long", timeStyle: "short" });
  const fileStem = `gripcheck_${session.id}`;
  const handMax = Math.max(sum.right.metrics.peak_kg, sum.left.metrics.peak_kg, 1);
  const marker = Math.min(98.5, Math.max(1.5, a.percentile));
  const anyFlag = max.some((t) => t.quality && t.quality !== "good");
  const applicableCutoffs = Object.entries(a.cutoffs).filter(([, c]) => c.applies);
  const rate = Math.round(session.trials.reduce((s, t) => s + t.rate_hz, 0) / session.trials.length);

  return (
    <div className="container">
      <header className="report-head">
        <div>
          <span className="eyebrow">Grip test report</span>
          <h1>{p.participant_id ? `Participant ${p.participant_id}` : "Grip strength results"}</h1>
          <div className="meta">
            <span className="tag">{dateText}</span>
            <span className="tag">
              {cap(p.sex)}, {p.age} y
            </span>
            <span className="tag">{cap(p.dominant)}-handed</span>
            <span className={`tag ${session.source === "device" ? "accent" : ""}`}>
              {session.source === "device" ? "Measured with the dynamometer" : "Simulated data"}
            </span>
            {session.source === "device" && <span className="tag mono">{rate} samples/s</span>}
          </div>
        </div>
        <div className="btn-row no-print">
          <button className="btn btn-primary" onClick={() => window.print()}>
            <IconPrint /> Print / save PDF
          </button>
          <button className="btn btn-secondary" onClick={() => download(`${fileStem}_summary.csv`, summaryCsv(session))}>
            <IconDownload /> Summary CSV
          </button>
          <button className="btn btn-secondary" onClick={() => download(`${fileStem}_raw.csv`, rawCsv(session))}>
            <IconDownload /> Raw CSV
          </button>
        </div>
      </header>

      <div style={{ display: "grid", gap: 12, marginBottom: 16 }}>
        {notSaved && (
          <div className="notice warn no-print">
            <IconWarn />
            <div>
              <b>Not saved.</b> This browser refused to store the session (private window or storage full). Download the CSVs or print the report
              before leaving the page.
            </div>
          </div>
        )}
        {session.source === "simulated" && (
          <div className="notice">
            <IconInfo />
            <div>
              <b>Simulated data.</b> These curves were generated by the simulator, not measured. They show how the analysis works, not anyone's real
              grip strength.
            </div>
          </div>
        )}
        {session.source === "device" && session.calibration !== "measured" && (
          <div className="notice warn">
            <IconWarn />
            <div>
              <b>Estimated calibration.</b> {CALIBRATION_NOTE}
            </div>
          </div>
        )}
        {p.injury && (
          <div className="notice">
            <IconInfo />
            <div>Pain or injury in the hand, wrist or elbow was reported in the last six months. Results may not reflect usual strength.</div>
          </div>
        )}
      </div>

      <div className="report-grid">
        {/* headline */}
        <section className="card headline span-5" aria-labelledby="h-best">
          <div style={{ display: "grid", gap: 6 }}>
            <span className="eyebrow" id="h-best">
              Best grip · {sum.stronger} hand
            </span>
            <div className="big">
              {sum.overall_peak_kg.toFixed(1)}
              <small>kg</small>
            </div>
            <p className="muted small">Highest of six maximal squeezes (filtered), the value the norms are based on.</p>
          </div>
          <div className="percentile-bar">
            <div className="percentile-track" role="img" aria-label={`About the ${a.percentile.toFixed(0)}th percentile`}>
              <i style={{ left: `${marker}%` }} />
            </div>
            <div className="percentile-scale">
              <span>0</span>
              <span>10</span>
              <span>25</span>
              <span>50</span>
              <span>75</span>
              <span>90</span>
              <span>100</span>
            </div>
          </div>
          <dl className="kv">
            <dt>Percentile band</dt>
            <dd>{a.band}</dd>
            <dt>Estimated percentile</dt>
            <dd>~{a.percentile.toFixed(0)}</dd>
            <dt>Z-score (age group)</dt>
            <dd>{a.z.toFixed(2)}</dd>
            <dt>T-score (young-adult peak)</dt>
            <dd>{a.t.toFixed(2)}</dd>
            <dt>Reference group</dt>
            <dd>
              {p.sex}, age {a.ref_age} · median {a.median} kg
            </dd>
          </dl>
          {applicableCutoffs.length > 0 && (
            <div style={{ display: "grid", gap: 8 }}>
              {applicableCutoffs.map(([name, c]) => (
                <div key={name} className={`notice ${c.below ? "warn" : "ok"}`}>
                  <div>
                    <b>{name}:</b> {c.text}
                  </div>
                </div>
              ))}
            </div>
          )}
        </section>

        <section className="card box span-7" aria-labelledby="h-centile">
          <div className="box-head">
            <h2 id="h-centile">Compared with {p.sex === "male" ? "men" : "women"} of all ages</h2>
            <span className="muted small">Dodds et al. 2014</span>
          </div>
          <CentileChart rows={normsFor(p.sex)} age={p.age} force={sum.overall_peak_kg} sexLabel={p.sex === "male" ? "men" : "women"} />
          <div className="legend">
            <span>
              <i style={{ background: "var(--band-outer)" }} /> 10th–90th centile
            </span>
            <span>
              <i style={{ background: "var(--band-inner)" }} /> 25th–75th
            </span>
            <span>
              <i style={{ background: "var(--muted)", height: 2 }} /> Median
            </span>
            <span>
              <i style={{ background: "var(--accent)", borderRadius: "50%", width: 10 }} /> This test
            </span>
          </div>
        </section>

        {/* hands */}
        <section className="card box span-5" aria-labelledby="h-hands">
          <h2 id="h-hands">Right vs left</h2>
          <div className="hand-bars">
            {(["right", "left"] as Hand[]).map((h) => {
              const m = sum[h].metrics;
              return (
                <div key={h} className={`hand-bar ${h}`}>
                  <div className="row">
                    <span>
                      <span className={`hand-dot ${h}`} /> {cap(h)}
                      {p.dominant === h ? " (dominant)" : ""}
                    </span>
                    <span className="mono">{m.peak_kg.toFixed(1)} kg</span>
                  </div>
                  <div className="track">
                    <i style={{ width: `${(m.peak_kg / handMax) * 100}%` }} />
                  </div>
                </div>
              );
            })}
          </div>
          <dl className="kv">
            <dt>Left / right ratio</dt>
            <dd>{fmt(sum.ratio, 2)}</dd>
            <dt>Weaker hand is weaker by</dt>
            <dd>{fmt(sum.weaker_pct)} %</dd>
            <dt>Trial-to-trial CV, right</dt>
            <dd>{fmt(sum.cv_pct.right)} %</dd>
            <dt>Trial-to-trial CV, left</dt>
            <dd>{fmt(sum.cv_pct.left)} %</dd>
          </dl>
          <p className="muted small">
            Reported without a verdict: the common “10 % rule” for the dominant hand is not supported consistently in the literature.
          </p>
        </section>

        <section className="card box span-7" aria-labelledby="h-best-curves">
          <div className="box-head">
            <h2 id="h-best-curves">Best squeeze, each hand</h2>
            <div className="legend">
              <span>
                <i style={{ background: "var(--right)" }} /> Right
              </span>
              <span>
                <i style={{ background: "var(--left)" }} /> Left
              </span>
            </div>
          </div>
          <ForceChart
            label={`Force-time curves of the best right (${sum.right.metrics.peak_kg.toFixed(1)} kg) and left (${sum.left.metrics.peak_kg.toFixed(1)} kg) squeezes.`}
            seconds={5}
            series={[
              { readings: sum.right.smooth, colorVar: "--right", markPeak: true, width: 2.4 },
              { readings: sum.left.smooth, colorVar: "--left", markPeak: true, width: 2.4 },
            ]}
          />
          <dl className="kv">
            <dt>Time to peak (R / L)</dt>
            <dd>
              {sum.right.metrics.time_to_peak_ms} / {sum.left.metrics.time_to_peak_ms} ms
            </dd>
            <dt>Rate of force development (R / L)</dt>
            <dd>
              {fmt(sum.right.metrics.rfd_n_per_s, 0)} / {fmt(sum.left.metrics.rfd_n_per_s, 0)} N/s
            </dd>
          </dl>
        </section>

        {/* fatigue */}
        {fatigue && (
          <section className="card box span-12" aria-labelledby="h-fatigue">
            <div className="box-head">
              <h2 id="h-fatigue">30-second hold · {fatigue.step.hand} hand</h2>
              <span className="mono">
                Fatigue index <b>{fmt(fatigue.metrics.fatigue_index_pct)} %</b>
              </span>
            </div>
            <ForceChart
              label={`Force over the 30 second hold. Peak ${fatigue.metrics.peak_kg.toFixed(1)} kg, fatigue index ${fmt(fatigue.metrics.fatigue_index_pct)} percent.`}
              seconds={32}
              height={220}
              width={1000}
              series={[{ readings: fatigue.smooth, colorVar: "--fatigue", markPeak: true, area: true, width: 2.2 }]}
            />
            <p className="muted small">
              Fatigue index = drop from the peak to the average of the final second of the 30 s squeeze, as a percentage of the peak.
            </p>
          </section>
        )}

        {/* every trial */}
        <section className="card box span-12" aria-labelledby="h-trials">
          <div className="box-head">
            <h2 id="h-trials">Every trial</h2>
            {anyFlag && (
              <span className="tag warn">
                <IconWarn size={14} /> Some trials were flagged
              </span>
            )}
          </div>
          <div className="table-wrap">
            <table className="data">
              <thead>
                <tr>
                  <th>Trial</th>
                  <th>Hand</th>
                  <th className="num">Peak kg</th>
                  <th className="num">Time to peak ms</th>
                  <th className="num">RFD N/s</th>
                  <th>Quality</th>
                </tr>
              </thead>
              <tbody>
                {session.trials.map((t, i) => {
                  const best = t === sum.right || t === sum.left;
                  return (
                    <tr key={i} className={best ? "best" : undefined}>
                      <td>{t.step.test === "fatigue" ? "30 s hold" : `Max ${t.step.trial}`}</td>
                      <td>
                        <span className={`hand-dot ${t.step.test === "fatigue" ? "fatigue" : t.step.hand}`} /> {cap(t.step.hand)}
                      </td>
                      <td className="num mono">
                        {t.metrics.peak_kg.toFixed(1)}
                        {best ? " ★" : ""}
                      </td>
                      <td className="num mono">{t.metrics.time_to_peak_ms}</td>
                      <td className="num mono">{fmt(t.metrics.rfd_n_per_s, 0)}</td>
                      <td>
                        {t.quality ? (
                          <span className={`tag ${t.quality === "good" ? "ok" : "warn"}`}>{QUALITY_TEXT[t.quality].title}</span>
                        ) : (
                          <span className="muted">–</span>
                        )}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
          <div className="trial-grid">
            {max.map((t, i) => (
              <div className="mini" key={i}>
                <div className="mini-head">
                  <span>
                    <span className={`hand-dot ${t.step.hand}`} /> {cap(t.step.hand)} {t.step.trial}
                  </span>
                  <span className="mono">{t.metrics.peak_kg.toFixed(1)} kg</span>
                </div>
                <ForceChart
                  compact
                  height={120}
                  width={320}
                  seconds={5}
                  yMax={Math.max(20, Math.ceil((handMax * 1.15) / 10) * 10)}
                  label={`${cap(t.step.hand)} hand trial ${t.step.trial}, peak ${t.metrics.peak_kg.toFixed(1)} kg`}
                  series={[
                    { readings: t.readings, colorVar: "--trace-faint", width: 1 },
                    { readings: t.smooth, colorVar: `--${t.step.hand}`, width: 1.8, markPeak: true },
                  ]}
                />
              </div>
            ))}
          </div>
          <p className="muted small">★ best trial per hand. Thin grey line: raw signal. Coloured line: filtered (4th-order Butterworth, zero phase).</p>
        </section>
      </div>

      <p className="muted small" style={{ marginTop: 24, maxWidth: "80ch" }}>
        Educational project, not a medical device and not a diagnosis. Norms: Dodds RM et al. (2014), PLoS ONE 9(12): e113637, British cohorts; the
        estimated percentile assumes a normal distribution within each age band. Cut-offs (EWGSOP2, AWGS 2019) are defined for adults aged 65 and
        over.
      </p>
      <div className="btn-row no-print" style={{ marginTop: 24 }}>
        <Link className="btn btn-primary" to="/test">
          New test
        </Link>
        <Link className="btn btn-ghost" to="/results">
          All results
        </Link>
      </div>
    </div>
  );
}
